/****************************************************************************
 * chip/rk3576/rk3576_reboot.h
 ****************************************************************************/

#ifndef __ARCH_ARM64_SRC_RK3576_RK3576_REBOOT_H
#define __ARCH_ARM64_SRC_RK3576_RK3576_REBOOT_H

/****************************************************************************
 * Included Files
 ****************************************************************************/

#include <stdbool.h>
#include <stdint.h>

/****************************************************************************
 * Public Function Prototypes
 ****************************************************************************/

/****************************************************************************
 * Name: rk3576_reboot_loader
 *
 * Description:
 *   写下载模式标志并全局软复位，让引导器启动时进 rockusb 下载模式。
 *   免去每次烧写都要手按 recovery 键。本函数不返回。
 *
 ****************************************************************************/

void rk3576_reboot_loader(void);

/****************************************************************************
 * Name: rk3576_reboot_normal
 *
 * Description:
 *   普通重启。本函数不返回。
 *
 ****************************************************************************/

void rk3576_reboot_normal(void);

/****************************************************************************
 * Name: rk3576_reboot_maskrom
 *
 * Description:
 *   重启进 BootROM 的下载模式（maskrom），等价于按住 recovery 键上电。
 *   比 rk3576_reboot_loader() 可靠：走 BootROM 自己的 USB，
 *   不经过 U-Boot 那个在本机枚举不出来的 rockusb gadget。
 *
 ****************************************************************************/

void rk3576_reboot_maskrom(void);

/****************************************************************************
 *
 *   读一次本次启动时重启模式寄存器的原值并锁存（之后再调返回同一个值）。
 *   必须在看门狗使能之前调用，见 rk3576_reboot.c 里 RK3576_REBOOT_WATCHDOG
 *   的说明。上电后的值不定（不一定是 0）。
 *
 ****************************************************************************/

uint32_t rk3576_bootmode_latch(void);

/****************************************************************************
 *
 *   本次启动是否由看门狗复位引起（依据重启模式寄存器）。
 *
 ****************************************************************************/

bool rk3576_bootmode_is_watchdog(void);

/****************************************************************************
 *
 *   看门狗使能时调用：往重启模式寄存器写 BOOT_WATCHDOG。之后若由看门狗
 *   复位，下次开机 rk3576_bootmode_is_watchdog() 为真；软件重启会把它
 *   改写成 NORMAL/LOADER。
 *
 ****************************************************************************/

void rk3576_bootmode_arm_watchdog(void);

#endif /* __ARCH_ARM64_SRC_RK3576_RK3576_REBOOT_H */
